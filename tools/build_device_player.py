#!/usr/bin/env python3
"""Embed the built phone instrument in firmware as deterministic gzip assets."""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PHONE = ROOT / "apps" / "beca-phone"
DIST = PHONE / "dist"
HEADER = ROOT / "device_player.h"
MIMES = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".wasm": "application/wasm",
    ".webmanifest": "application/manifest+json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
}


def render_header() -> tuple[str, int, int]:
    required = {"index.html", "app.js", "app.css", "protocol.js", "phone-audio.js", "wifi-provider.js", "beca-synth.wasm"}
    files = sorted(p for p in DIST.rglob("*") if p.is_file() and p.suffix in MIMES)
    names = {p.relative_to(DIST).as_posix() for p in files}
    if not required <= names:
        raise SystemExit("Build phone assets first; missing: " + ", ".join(sorted(required - names)))
    lines = ["// Generated by tools/build_device_player.py; do not edit.", "#pragma once", "#include <Arduino.h>", "",
             "struct DevicePlayerAsset {", "  const char* path;", "  const char* mime;", "  const uint8_t* data;", "  size_t size;", "};", ""]
    digest = hashlib.sha256()
    entries = []
    compressed_size = raw_size = 0
    for i, file in enumerate(files):
        name = file.relative_to(DIST).as_posix()
        raw = file.read_bytes()
        source = PHONE / name
        if not source.is_file() or source.read_bytes() != raw:
            raise SystemExit(f"Stale phone build: {name}. Rebuild before embedding.")
        digest.update(name.encode() + b"\0" + raw)
        packed = gzip.compress(raw, compresslevel=9, mtime=0)
        symbol = f"DEVICE_PLAYER_ASSET_{i}"
        lines.append(f"// {name}: {len(raw)} bytes, gzip {len(packed)} bytes")
        lines.append(f"static const uint8_t {symbol}[] PROGMEM = {{")
        for offset in range(0, len(packed), 20):
            lines.append("  " + ",".join(f"0x{x:02x}" for x in packed[offset:offset + 20]) + ",")
        lines.extend(["};", ""])
        entries.append(f"  {{{json.dumps('/play/' + name)}, {json.dumps(MIMES[file.suffix])}, {symbol}, sizeof({symbol})}},")
        compressed_size += len(packed)
        raw_size += len(raw)
    lines.extend([f"// Source SHA256: {digest.hexdigest()}", "static const DevicePlayerAsset DEVICE_PLAYER_ASSETS[] = {", *entries,
                  "};", "static const size_t DEVICE_PLAYER_ASSET_COUNT = sizeof(DEVICE_PLAYER_ASSETS) / sizeof(DEVICE_PLAYER_ASSETS[0]);", ""])
    return "\n".join(lines), raw_size, compressed_size


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the current generated header without writing it.")
    args = parser.parse_args()
    text, raw, packed = render_header()
    if args.check:
        if not HEADER.is_file() or HEADER.read_text() != text:
            raise SystemExit("device_player.h is stale; run python3 tools/build_device_player.py")
        print(f"Device player verified: {raw} bytes, gzip {packed} bytes")
    else:
        HEADER.write_text(text)
        print(f"Generated {HEADER.name}: {raw} bytes, gzip {packed} bytes")


if __name__ == "__main__":
    main()
